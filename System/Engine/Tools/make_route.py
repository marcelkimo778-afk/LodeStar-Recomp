"""Generate a benchmark route (the format of the F9 recorder, Engine/Runtime/src/sw_hid.c): exploration-like input
for a save that has no recorded route - running in changing directions while the camera keeps sweeping, a full
camera turn every 15 s (new content streams in), short stops.

    python Engine/Tools/make_route.py <route dir> [seconds]

The route dir must already hold save/ (main, main2, backup); input.txt is written next to it."""
import math
import sys
from pathlib import Path

M = 32767
out = Path(sys.argv[1])
secs = float(sys.argv[2]) if len(sys.argv) > 2 else 90.0
lines = ["# generated by Engine/Tools/make_route.py: exploration (run + camera sweeps + 360 turns); t_ms buttons lx ly rx ry"]
step = 0.05                          # 20 changes a second, like a real stick
t = 0.0
while t < secs:
    cyc = t % 15.0
    heading = (t // 15.0) * 1.1      # each 15 s block runs in another direction
    if t < 2.0:                      # stand still first
        lx = ly = rx = ry = 0
    elif cyc < 10.0:                 # run, camera sweeping left and right
        lx = int(M * math.sin(heading))
        ly = int(M * math.cos(heading))
        rx = int(M * 0.85 * math.sin(t * 1.3))
        ry = int(M * 0.25 * math.sin(t * 0.7))
    elif cyc < 13.0:                 # stop and turn the camera all the way round
        lx = ly = 0
        rx, ry = M, 0
    else:                            # walk slowly, camera still
        lx, ly, rx, ry = 0, int(M * 0.45), 0, 0
    lines.append(f"{int(t * 1000)} 0 {lx} {ly} {rx} {ry}")
    t += step
lines.append(f"{int(secs * 1000)} 0 0 0 0 0")
(out / "input.txt").write_text("\n".join(lines) + "\n", encoding="ascii")
print(f"{out / 'input.txt'}: {len(lines) - 1} input changes, {secs:.0f} s")
