"""Compiles the frame generation shaders (Engine/Runtime/gfx/fg_shaders/*.comp) into
Engine/Runtime/gfx/vk/sw_framegen_spv.h with the Vulkan SDK's glslc.  The header is checked in, so a build needs this
only after a shader changed: python Engine/Tools/build_fg_shaders.py"""
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "Engine" / "Runtime" / "gfx" / "fg_shaders"
OUT = ROOT / "Engine" / "Runtime" / "gfx" / "vk" / "sw_framegen_spv.h"
NAMES = ("fg_down", "fg_search", "fg_filter", "fg_interp")


def glslc() -> str:
    sdk = os.environ.get("VULKAN_SDK")
    for c in ([str(Path(sdk) / "Bin" / "glslc.exe")] if sdk else []) + [shutil.which("glslc") or ""]:
        if c and Path(c).is_file():
            return c
    sys.exit("glslc not found: install the Vulkan SDK")


def main() -> None:
    cc = glslc()
    lines = ["// Generated by Engine/Tools/build_fg_shaders.py from Engine/Runtime/gfx/fg_shaders; do not edit.",
             "#pragma once", "#include <stdint.h>"]
    with tempfile.TemporaryDirectory() as tmp:
        for n in NAMES:
            src = SRC / (n + ".comp")
            spv = Path(tmp) / (n + ".spv")
            r = subprocess.run([cc, "-O", "--target-env=vulkan1.3", "-I", str(SRC), str(src), "-o", str(spv)],
                               capture_output=True, text=True)
            if r.returncode:
                sys.exit(f"{src.name}:\n{r.stderr}")
            d = spv.read_bytes()
            words = [int.from_bytes(d[i:i + 4], "little") for i in range(0, len(d), 4)]
            lines.append(f"// {n}.comp sha256 {hashlib.sha256(src.read_bytes()).hexdigest()}")
            lines.append(f"static const uint32_t {n}_spv[] = {{")
            for i in range(0, len(words), 8):
                lines.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",")
            lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.name}: {len(NAMES)} shaders")


if __name__ == "__main__":
    main()
